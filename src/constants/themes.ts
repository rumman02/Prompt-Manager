// Theme definitions for Prompt Manager
// Each theme provides light and dark variants with full color tokens.
// Colors are stored as hex and converted to HSL at runtime by SettingsContext.

export interface ThemeColors {
  // Surfaces
  background: string;
  foreground: string;
  card: string;
  cardForeground: string;
  popover: string;
  popoverForeground: string;
  // Accent
  primary: string;
  primaryForeground: string;
  // Secondary / grouped
  secondary: string;
  secondaryForeground: string;
  muted: string;
  mutedForeground: string;
  accent: string;
  accentForeground: string;
  // Semantic
  destructive: string;
  destructiveForeground: string;
  // Borders
  border: string;
  input: string;
  ring: string;
  // Extended
  textSecondary: string;
  accent2: string;          // split into --accent-2-h/s/l at runtime
  // Code zone
  codeBg: string;
  codeBorder: string;
  tokenSat: string;         // percentage, e.g. "70%"
  tokenBgL: string;         // percentage, e.g. "95%"
  tokenFgL: string;         // percentage, e.g. "30%"
  tokenBorderL: string;     // percentage, e.g. "80%"
  // Status
  success: string;
  warning: string;
  tertiaryLabel: string;
  // Shadcn sidebar tokens — optional, not yet consumed by SettingsContext,
  // kept so every theme fully describes the shadcn variable set.
  sidebarBackground?: string;
  sidebarForeground?: string;
  sidebarPrimary?: string;
  sidebarPrimaryForeground?: string;
  sidebarAccent?: string;
  sidebarAccentForeground?: string;
  sidebarBorder?: string;
  sidebarRing?: string;
  // Shadcn chart tokens — optional (same reason).
  chart1?: string;
  chart2?: string;
  chart3?: string;
  chart4?: string;
  chart5?: string;
}

export interface ThemeVariant {
  name: string;
  colors: ThemeColors;
}

export interface Theme {
  id: string;
  name: string;
  description: string;
  variants: {
    light: ThemeVariant;
    dark: ThemeVariant;
  };
}

